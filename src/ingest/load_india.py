"""India-context data (Phase 8): a real India test set, and Indian fact-checks for the evidence index.

All three come from the ComplexDataLab "Misinfo_Datasets" collection on Hugging Face, which re-hosts
published datasets in one shared schema (papers and licences: DATASETS.md). The four training
datasets are unchanged; nothing here is used to train a model.

    IFND        Sharma & Garg 2021. English Indian news headlines 2013-2021: 37,785 true (Tribune,
                The Statesman, ThePrint, Indian Express ...) and 18,913 "fake". TEST data only, after
                cleaning, because the raw labels do not measure claim checking:
                - 11,321 fakes (60%) are generated by the authors ("AUGMENT" in the source field):
                  true headlines with words swapped, not misinformation anyone shared -> dropped;
                - about half of the other fakes are fact-checkers' headlines ("Fact Check: viral video
                  of X is fake"): a true statement about a debunk, not the claim -> every row with
                  debunk wording dropped, from both labels, so the filter is not a label proxy;
                - exact duplicates dropped.
    FakeCovid   Shahi & Nandini 2020. COVID-19 fact-checks (Poynter database). The Indian English part:
                748 fact-checks by Factly, BOOM, The Quint, India Today, Vishvas News ... (Jan-Jun 2020),
                almost all False/Misleading. Train+val -> evidence passages; test -> a fake-only test.
    MultiClaim  Pikuliak et al. 2023. 31k fact-checked social-media posts, mostly AFP, many countries,
                with English translations. Train+val -> evidence passages.

Run from `news-credibility/`:
    python -m src.ingest.load_india     # downloads (~55 MB) if missing -> data/processed/india/*.parquet
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

from src.ingest.load_raw import domain_of

ROOT = Path(__file__).resolve().parents[2]
RAW_DIR = ROOT / "data" / "raw" / "misinfo_datasets"
OUT_DIR = ROOT / "data" / "processed" / "india"
SUMMARY = ROOT / "reports" / "india_data_summary.json"
HF_REPO = "ComplexDataLab/Misinfo_Datasets"
DATASETS = ("IFND", "fakecovid", "multiclaim")
SPLITS = {"train": "train", "validation": "val", "test": "test"}

# A fact-checker's headline, not a claim as it circulated: "Fact Check: ...", "... is fake", "viral video ...".
DEBUNK_RE = re.compile(
    r"fact[- ]?check|\b(?:fake|false|hoax|fabricated|morphed|doctored|misleading)\b"
    r"|\b(?:viral|claims?|claimed|claiming|shared as|passed off)\b|\bold (?:video|photo|image|picture)\b|\bunrelated\b",
    re.IGNORECASE,
)


def download(names=DATASETS, raw_dir: Path = RAW_DIR) -> None:
    """Fetch the parquet files that are missing (public repository, no account needed)."""
    from huggingface_hub import hf_hub_download

    for name in names:
        for split in SPLITS:
            if not (raw_dir / name / f"{name}_{split}.parquet").exists():
                hf_hub_download(HF_REPO, f"{name}/{name}_{split}.parquet", repo_type="dataset", local_dir=raw_dir)


def read(name: str, raw_dir: Path = RAW_DIR) -> pd.DataFrame:
    """All three splits of one dataset, with `split` in the project's names (train/val/test)."""
    frames = [pd.read_parquet(raw_dir / name / f"{name}_{s}.parquet").assign(split=ours) for s, ours in SPLITS.items()]
    return pd.concat(frames, ignore_index=True)


def verdict_score(label: object) -> float:
    """A fact-checker's verdict word -> credible in [0, 1] (Phase 2 scale); NaN if it is no verdict
    ("Explanatory", "No evidence", "na")."""
    s = re.sub(r"[^a-z ]", " ", str(label).lower())
    if re.search(r"\b(partly|partially|half|mixture|mixed|missing context)\b", s):
        return 0.5
    if re.search(r"\b(false|fake|misleading|altered|incorrect|pants on fire|wrong)\b", s):
        return 0.0
    if re.search(r"\b(true|correct|accurate)\b", s):
        return 1.0
    return np.nan


def clean_ifnd(df: pd.DataFrame) -> tuple[pd.DataFrame, dict]:
    """IFND rows usable as a claim-checking test set, and the count after each step."""
    steps = {"raw": len(df), "raw_true": int((df["label"] == "true").sum()), "raw_fake": int((df["label"] == "fake").sum())}
    df = df[~((df["label"] == "fake") & (df["web"] == "AUGMENT"))]
    steps["after_dropping_generated_fakes"] = len(df)
    debunk = df["claim"].str.contains(DEBUNK_RE)
    steps["debunk_wording_dropped"] = {lab: int((debunk & (df["label"] == lab)).sum()) for lab in ("true", "fake")}
    df = df[~debunk]
    key = df["claim"].str.strip().str.lower()
    steps["duplicates_dropped"] = int(key.duplicated().sum())
    df = df[~key.duplicated()]
    out = pd.DataFrame({
        "item_id": [f"ifnd_{i}" for i in df.index], "dataset": "ifnd", "text": df["claim"].str.strip(),
        "credible": (df["label"] == "true").astype(float), "split": df["split"],
        "subject": df["subject"], "source": df["web"], "image_url": df["image"],
    }).reset_index(drop=True)
    steps["final"] = {f"{s}/{'true' if c else 'fake'}": int(n)
                      for (s, c), n in out.groupby(["split", "credible"]).size().items()}
    return out, steps


def _date(value: object) -> str | None:
    d = pd.to_datetime(str(value), format="%Y/%m/%d", errors="coerce")
    return None if pd.isna(d) else d.strftime("%Y-%m-%d")


def fakecovid_india(df: pd.DataFrame) -> pd.DataFrame:
    """Indian English COVID-19 fact-checks: the claim as it circulated + verdict + article."""
    df = df[(df["country"] == "India") & (df["language"] == "en")]
    return pd.DataFrame({
        "item_id": [f"fakecovid_{i}" for i in df.index], "dataset": "fakecovid_india", "text": df["claim"].str.strip(),
        "credible": df["label"].map(verdict_score), "label_raw": df["label"], "split": df["split"],
        "fact_checker": df["fact_check_url"].map(domain_of), "fact_check_url": df["fact_check_url"],
        "date": df["date"].map(_date), "title": df["article_title"].replace("na", None),
    }).reset_index(drop=True)


def multiclaim_en(df: pd.DataFrame) -> pd.DataFrame:
    """Fact-checked posts with an English translation of the claim and a verdict."""
    df = df[df["claim_en"].astype(str).str.strip().ne("") & df["claim_en"].ne("na")]
    out = pd.DataFrame({
        "item_id": [f"multiclaim_{i}" for i in df.index], "dataset": "multiclaim", "text": df["claim_en"].str.strip(),
        "credible": df["label"].map(verdict_score), "label_raw": df["label"], "split": df["split"],
        "fact_checker": df["fact_check_url"].map(domain_of), "fact_check_url": df["fact_check_url"],
        "date": None, "title": None,
    })
    return out[out["credible"].notna()].reset_index(drop=True)


def build(raw_dir: Path = RAW_DIR, out_dir: Path = OUT_DIR) -> dict:
    download(raw_dir=raw_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    ifnd, steps = clean_ifnd(read("IFND", raw_dir))
    fc = fakecovid_india(read("fakecovid", raw_dir))
    mc = multiclaim_en(read("multiclaim", raw_dir))
    for name, df in (("ifnd_clean", ifnd), ("fakecovid_india", fc), ("multiclaim_en", mc)):
        df.to_parquet(out_dir / f"{name}.parquet", index=False)
    summary = {
        "ifnd": steps,
        "fakecovid_india": {"rows": len(fc), "by_split_credible": {f"{s}/{c}": int(n) for (s, c), n in
                                                                 fc.groupby(["split", fc["credible"].fillna(-1)]).size().items()},
                            "fact_checkers": fc["fact_checker"].value_counts().to_dict()},
        "multiclaim_en": {"rows": len(mc), "by_split": mc["split"].value_counts().to_dict(),
                          "credible": mc["credible"].value_counts().to_dict()},
    }
    SUMMARY.parent.mkdir(parents=True, exist_ok=True)
    SUMMARY.write_text(json.dumps(summary, indent=2))
    return summary


if __name__ == "__main__":
    print(json.dumps(build(), indent=2))
