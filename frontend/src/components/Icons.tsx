const TONE_ICONS: Record<Tone, (p: IconProps) => ReactNode> = {
  good: CheckCircle,
  ok: CheckCircle,
  warn: AlertTriangle,
  bad: XCircle,
  neutral: HelpCircle,
}

/** The icon that goes with a status colour, so the status never depends on colour alone. */
export function ToneIcon({ tone, ...rest }: IconProps & { tone: Tone }) {
  const Glyph = TONE_ICONS[tone]
  return <Glyph {...rest} />
}
