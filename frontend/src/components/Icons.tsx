// A small set of line icons, drawn inline so the app ships no icon library. Each is decorative
// (aria-hidden): the word next to it always carries the meaning.

import type { ReactNode, SVGProps } from 'react'
import type { Tone } from '../translate/types'

type IconProps = SVGProps<SVGSVGElement> & { size?: number }

function Icon({ size = 20, children, ...rest }: IconProps & { children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      {children}
    </svg>
  )
}

